-- Idempotent compatibility migration. Existing order/payment records are never rewritten.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF DB_NAME() <> 'T_Winkle' THROW 51200, 'Expected T_Winkle database.', 1;
BEGIN TRY
 BEGIN TRANSACTION;
 IF NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.PAYMENTS') AND name='CK_PAYMENTS_METHOD')
    OR NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE parent_object_id=OBJECT_ID('dbo.ORDERS') AND name='CK_ORDERS_PAYMENT_METHOD')
   THROW 51201, 'Inspect payment method constraints before applying this migration.', 1;
 IF EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_PAYMENTS_METHOD' AND definition NOT LIKE '%BANKING%')
 BEGIN
  ALTER TABLE dbo.PAYMENTS DROP CONSTRAINT CK_PAYMENTS_METHOD;
  ALTER TABLE dbo.PAYMENTS WITH CHECK ADD CONSTRAINT CK_PAYMENTS_METHOD CHECK(method IN('COD','BANKING','VNPAY','MOMO'));
 END;
 IF EXISTS(SELECT 1 FROM sys.check_constraints WHERE name='CK_ORDERS_PAYMENT_METHOD' AND definition NOT LIKE '%BANKING%')
 BEGIN
  ALTER TABLE dbo.ORDERS DROP CONSTRAINT CK_ORDERS_PAYMENT_METHOD;
  ALTER TABLE dbo.ORDERS WITH CHECK ADD CONSTRAINT CK_ORDERS_PAYMENT_METHOD CHECK(payment_method IN('COD','BANKING','VNPAY','MOMO'));
 END;
 ALTER TABLE dbo.PAYMENTS WITH CHECK CHECK CONSTRAINT CK_PAYMENTS_METHOD;
 ALTER TABLE dbo.ORDERS WITH CHECK CHECK CONSTRAINT CK_ORDERS_PAYMENT_METHOD;
 SELECT name,definition,is_disabled,is_not_trusted FROM sys.check_constraints WHERE name IN('CK_PAYMENTS_METHOD','CK_ORDERS_PAYMENT_METHOD');
 COMMIT;
END TRY
BEGIN CATCH
 IF @@TRANCOUNT>0 ROLLBACK;
 THROW;
END CATCH;
