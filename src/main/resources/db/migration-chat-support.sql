-- SQL Server, additive and idempotent. AI history intentionally has no table.
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;
SET NUMERIC_ROUNDABORT OFF;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.SIZE_CHARTS','U') IS NULL
CREATE TABLE dbo.SIZE_CHARTS (
 id BIGINT IDENTITY PRIMARY KEY, name NVARCHAR(180) NOT NULL,
 brand_id INT NULL REFERENCES dbo.BRANDS(id), category_id INT NULL REFERENCES dbo.CATEGORIES(id),
 product_id INT NULL REFERENCES dbo.PRODUCTS(id), gender_scope VARCHAR(30) NULL,
 source_type VARCHAR(30) NOT NULL, source_reference NVARCHAR(500) NULL, notes NVARCHAR(1000) NULL,
 is_active BIT NOT NULL DEFAULT 1, created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 updated_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT CK_SIZE_SOURCE CHECK (source_type IN ('OFFICIAL','APPROVED','TWINKLE_REFERENCE'))
);
IF OBJECT_ID('dbo.SIZE_CHART_ENTRIES','U') IS NULL
CREATE TABLE dbo.SIZE_CHART_ENTRIES (
 id BIGINT IDENTITY PRIMARY KEY, size_chart_id BIGINT NOT NULL REFERENCES dbo.SIZE_CHARTS(id),
 foot_length_min_cm DECIMAL(5,2) NOT NULL, foot_length_max_cm DECIMAL(5,2) NOT NULL,
 eu_size VARCHAR(50) NOT NULL, us_men_size VARCHAR(20) NULL, us_women_size VARCHAR(20) NULL,
 uk_size VARCHAR(20) NULL, jp_cm DECIMAL(5,2) NULL, width_code VARCHAR(20) NULL,
 recommendation_note NVARCHAR(500) NULL, sort_order INT NOT NULL DEFAULT 0,
 CONSTRAINT CK_SIZE_RANGE CHECK (foot_length_min_cm > 0 AND foot_length_max_cm >= foot_length_min_cm)
);
-- No unverifiable chart entries are seeded. Missing approved data returns INSUFFICIENT_SIZE_DATA.
IF OBJECT_ID('dbo.STORE_STAFF_ASSIGNMENTS','U') IS NULL
CREATE TABLE dbo.STORE_STAFF_ASSIGNMENTS (
 id BIGINT IDENTITY PRIMARY KEY, store_id INT NOT NULL REFERENCES dbo.STORES(store_id),
 user_email VARCHAR(100) NOT NULL REFERENCES dbo.USERS(email), active BIT NOT NULL DEFAULT 1,
 assigned_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT UQ_STORE_STAFF UNIQUE(store_id,user_email)
);
IF NOT EXISTS (SELECT 1 FROM dbo.ROLES WHERE name='ROLE_SUPPORT')
INSERT dbo.ROLES(name) VALUES ('ROLE_SUPPORT');
IF OBJECT_ID('dbo.SUPPORT_CONVERSATIONS','U') IS NULL
CREATE TABLE dbo.SUPPORT_CONVERSATIONS (
 id BIGINT IDENTITY PRIMARY KEY, user_email VARCHAR(100) NOT NULL REFERENCES dbo.USERS(email),
 store_id INT NOT NULL REFERENCES dbo.STORES(store_id), order_id BIGINT NULL REFERENCES dbo.ORDERS(id),
 product_id INT NULL REFERENCES dbo.PRODUCTS(id), source VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 handoff_reason VARCHAR(30) NULL, handoff_summary NVARCHAR(1000) NULL,
 created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(), updated_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 last_message_at DATETIME2 NULL, closed_at DATETIME2 NULL,
 CONSTRAINT CK_SUPPORT_SOURCE CHECK (source IN ('AI_HANDOFF','DIRECT')),
 CONSTRAINT CK_SUPPORT_STATUS CHECK (status IN ('OPEN','CLOSED')),
 CONSTRAINT CK_HANDOFF_REASON CHECK (handoff_reason IS NULL OR handoff_reason IN
 ('PRODUCT_DEFECT','WRONG_ITEM','MISSING_ITEM','REFUND_REQUEST','COMPLAINT','ORDER_PROBLEM','AI_UNRESOLVED','OTHER'))
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.SUPPORT_CONVERSATIONS') AND name='UX_SUPPORT_OPEN')
CREATE UNIQUE INDEX UX_SUPPORT_OPEN ON dbo.SUPPORT_CONVERSATIONS(user_email,store_id,order_id) WHERE status='OPEN';
IF OBJECT_ID('dbo.SUPPORT_MESSAGES','U') IS NULL
CREATE TABLE dbo.SUPPORT_MESSAGES (
 id BIGINT IDENTITY PRIMARY KEY, conversation_id BIGINT NOT NULL REFERENCES dbo.SUPPORT_CONVERSATIONS(id),
 sender_type VARCHAR(20) NOT NULL, sender_email VARCHAR(100) NULL REFERENCES dbo.USERS(email),
 content NVARCHAR(2000) NOT NULL, client_message_id VARCHAR(36) NULL,
 created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
 CONSTRAINT CK_SUPPORT_SENDER CHECK (sender_type IN ('USER','STAFF','SYSTEM'))
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.SUPPORT_MESSAGES') AND name='UX_SUPPORT_MESSAGE_RETRY')
CREATE UNIQUE INDEX UX_SUPPORT_MESSAGE_RETRY ON dbo.SUPPORT_MESSAGES(conversation_id,sender_email,client_message_id)
 WHERE client_message_id IS NOT NULL;
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.SUPPORT_MESSAGES') AND name='IX_SUPPORT_MESSAGE_HISTORY')
CREATE INDEX IX_SUPPORT_MESSAGE_HISTORY ON dbo.SUPPORT_MESSAGES(conversation_id,id);
COMMIT;
