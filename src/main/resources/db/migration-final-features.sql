-- Additive SQL Server migration; existing review ownership is the validated OrderItem.
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
SET ANSI_PADDING ON;
SET ANSI_WARNINGS ON;
SET CONCAT_NULL_YIELDS_NULL ON;
SET ARITHABORT ON;
SET NUMERIC_ROUNDABORT OFF;
BEGIN TRANSACTION;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.REVIEWS') AND name='UQ_FINAL_REVIEW_ITEM')
 CREATE UNIQUE INDEX UQ_FINAL_REVIEW_ITEM ON dbo.REVIEWS(id,order_item_id);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.ORDER_ITEMS') AND name='UQ_FINAL_ITEM_STORE')
 CREATE UNIQUE INDEX UQ_FINAL_ITEM_STORE ON dbo.ORDER_ITEMS(id,store_id);
IF OBJECT_ID('dbo.REVIEW_RESPONSES','U') IS NULL
 CREATE TABLE dbo.REVIEW_RESPONSES(
  id BIGINT IDENTITY PRIMARY KEY,
  review_id BIGINT NOT NULL UNIQUE,
  order_item_id BIGINT NOT NULL,
  store_id INT NOT NULL REFERENCES dbo.STORES(store_id),
  responder_email VARCHAR(100) NOT NULL REFERENCES dbo.USERS(email),
  content NVARCHAR(2000) NOT NULL,
  created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
  updated_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
  CONSTRAINT FK_RESPONSE_REVIEW_ITEM FOREIGN KEY(review_id,order_item_id) REFERENCES dbo.REVIEWS(id,order_item_id),
  CONSTRAINT FK_RESPONSE_ITEM_STORE FOREIGN KEY(order_item_id,store_id) REFERENCES dbo.ORDER_ITEMS(id,store_id),
  CONSTRAINT CK_RESPONSE_CONTENT CHECK(LEN(LTRIM(RTRIM(content)))>0)
 );
IF OBJECT_ID('dbo.STORE_REPORTS','U') IS NULL
 CREATE TABLE dbo.STORE_REPORTS(
  id BIGINT IDENTITY PRIMARY KEY,
  store_id INT NOT NULL REFERENCES dbo.STORES(store_id),
  created_by_email VARCHAR(100) NOT NULL REFERENCES dbo.USERS(email),
  report_type VARCHAR(20) NOT NULL,
  file_name VARCHAR(150) NOT NULL,
  content_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL,
  sha256 CHAR(64) NOT NULL,
  file_data VARBINARY(MAX) NOT NULL,
  filter_snapshot NVARCHAR(4000) NOT NULL,
  sort_snapshot NVARCHAR(500) NOT NULL,
  columns_snapshot NVARCHAR(2000) NOT NULL,
  row_count INT NOT NULL,
  created_at DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
  sent_at DATETIME2 NULL,
  CONSTRAINT CK_REPORT_TYPE CHECK(report_type IN('PRODUCTS','INVENTORY','ORDERS','PAYMENTS','DASHBOARD')),
  CONSTRAINT CK_REPORT_SIZE CHECK(file_size=DATALENGTH(file_data) AND file_size>0 AND file_size<=20971520),
  CONSTRAINT CK_REPORT_ROWS CHECK(row_count>=0)
 );
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.STORE_REPORTS') AND name='IX_REPORT_SENT')
 CREATE INDEX IX_REPORT_SENT ON dbo.STORE_REPORTS(sent_at DESC,id DESC) INCLUDE(store_id,report_type) WHERE sent_at IS NOT NULL;
COMMIT;
