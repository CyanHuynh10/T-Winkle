SELECT 'USERS' AS table_name,COUNT_BIG(*) AS residue FROM USERS WHERE email LIKE 'TWADMINTEST%' OR username LIKE 'TWADMINTEST%'
UNION ALL SELECT 'STORES',COUNT_BIG(*) FROM STORES WHERE slug LIKE 'TWADMINTEST%' OR name LIKE 'TWADMINTEST%'
UNION ALL SELECT 'PRODUCTS',COUNT_BIG(*) FROM PRODUCTS WHERE slug LIKE 'TWADMINTEST%' OR name LIKE 'TWADMINTEST%'
UNION ALL SELECT 'PRODUCT_VARIANTS',COUNT_BIG(*) FROM PRODUCT_VARIANTS WHERE sku LIKE 'TWADMINTEST%'
UNION ALL SELECT 'CATEGORIES',COUNT_BIG(*) FROM CATEGORIES WHERE slug LIKE 'TWADMINTEST%' OR name LIKE 'TWADMINTEST%'
UNION ALL SELECT 'BRANDS',COUNT_BIG(*) FROM BRANDS WHERE slug LIKE 'TWADMINTEST%' OR name LIKE 'TWADMINTEST%'
UNION ALL SELECT 'ORDERS',COUNT_BIG(*) FROM ORDERS WHERE order_code LIKE 'TWADMINTEST%'
UNION ALL SELECT 'COUPONS',COUNT_BIG(*) FROM COUPONS WHERE code LIKE 'TWADMINTEST%'
UNION ALL SELECT 'PROMOTIONS',COUNT_BIG(*) FROM PROMOTIONS WHERE name LIKE 'TWADMINTEST%'
UNION ALL SELECT 'SUPPORT_MESSAGES',COUNT_BIG(*) FROM SUPPORT_MESSAGES WHERE content LIKE 'TWADMINTEST%'
UNION ALL SELECT 'ADMIN_AUDIT_LOG',COUNT_BIG(*) FROM ADMIN_AUDIT_LOG WHERE actor_email LIKE 'TWADMINTEST%'
UNION ALL SELECT 'INVENTORY_MOVEMENTS',COUNT_BIG(*) FROM INVENTORY_MOVEMENTS WHERE performed_by LIKE 'TWADMINTEST%'
UNION ALL SELECT 'PAYMENT_VERIFICATIONS',COUNT_BIG(*) FROM PAYMENT_VERIFICATIONS WHERE reported_by LIKE 'TWADMINTEST%' OR reviewed_by LIKE 'TWADMINTEST%';
SELECT name FROM sys.foreign_keys WHERE is_disabled=1 OR is_not_trusted=1;
SELECT name FROM sys.check_constraints WHERE is_disabled=1 OR is_not_trusted=1;
